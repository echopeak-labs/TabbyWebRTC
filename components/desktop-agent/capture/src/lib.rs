#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum PixelFormat {
    BGRA,
    NV12,
}

#[derive(Debug, Clone)]
pub struct Frame {
    pub data: Vec<u8>,
    pub format: PixelFormat,
    pub width: u32,
    pub height: u32,
    pub timestamp_us: u64,
}

pub trait Capturable: Send {
    fn id(&self) -> &str;
    fn name(&self) -> &str;
    fn width(&self) -> u32;
    fn height(&self) -> u32;
    fn start(&mut self) -> anyhow::Result<()>;
    fn stop(&mut self);
    fn next_frame(&mut self) -> anyhow::Result<Frame>;
    fn capture_thumbnail(&mut self) -> anyhow::Result<Vec<u8>>;
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SourceKind {
    Display,
    App,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SourceDescriptor {
    pub id: String,
    pub name: String,
    pub kind: SourceKind,
    pub width: u32,
    pub height: u32,
}

pub fn enumerate_sources() -> anyhow::Result<Vec<SourceDescriptor>> {
    #[cfg(target_os = "linux")]
    return linux::enumerate_sources();
    #[cfg(target_os = "windows")]
    return windows::enumerate_sources();
    #[cfg(target_os = "macos")]
    return macos::enumerate_sources();
    #[cfg(not(any(target_os = "linux", target_os = "windows", target_os = "macos")))]
    anyhow::bail!("unsupported platform")
}

pub fn capture_thumbnail(source_id: &str) -> anyhow::Result<Vec<u8>> {
    #[cfg(target_os = "linux")]
    return linux::capture_thumbnail(source_id);
    #[cfg(target_os = "windows")]
    return windows::capture_thumbnail(source_id);
    #[cfg(target_os = "macos")]
    return macos::capture_thumbnail(source_id);
    #[cfg(not(any(target_os = "linux", target_os = "windows", target_os = "macos")))]
    {
        let _ = source_id;
        anyhow::bail!("unsupported platform")
    }
}

pub fn create_capturable(
    source_id: &str,
    config: &CaptureConfig,
) -> anyhow::Result<Box<dyn Capturable>> {
    #[cfg(target_os = "linux")]
    return linux::create_capturable(source_id, config);
    #[cfg(target_os = "windows")]
    return windows::create_capturable(source_id, config);
    #[cfg(target_os = "macos")]
    return macos::create_capturable(source_id, config);
    #[cfg(not(any(target_os = "linux", target_os = "windows", target_os = "macos")))]
    {
        let _ = (source_id, config);
        anyhow::bail!("unsupported platform")
    }
}

